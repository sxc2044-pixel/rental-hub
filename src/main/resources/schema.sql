CREATE TABLE IF NOT EXISTS t_user (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, account VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, recovery_hash VARCHAR(100) NOT NULL,
 name VARCHAR(40) NOT NULL, role VARCHAR(16) NOT NULL DEFAULT 'STUDENT',
 school VARCHAR(80) NOT NULL DEFAULT '', phone VARCHAR(20) NOT NULL DEFAULT '',
 certification VARCHAR(16) NOT NULL DEFAULT 'NONE', cert_file VARCHAR(80), cert_note VARCHAR(255),
 enabled BOOLEAN NOT NULL DEFAULT TRUE, session_version INT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS t_dictionary (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, category VARCHAR(16) NOT NULL,
 label VARCHAR(40) NOT NULL, min_value DECIMAL(10,2), max_value DECIMAL(10,2),
 UNIQUE(category,label)
);
CREATE TABLE IF NOT EXISTS t_house (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(100) NOT NULL,
 region VARCHAR(40) NOT NULL, address VARCHAR(160) NOT NULL,
 rent DECIMAL(10,2) NOT NULL, area DECIMAL(8,2) NOT NULL, layout VARCHAR(40) NOT NULL,
 facilities VARCHAR(255) NOT NULL, description VARCHAR(2000) NOT NULL,
 image VARCHAR(100) NOT NULL, owner_name VARCHAR(40) NOT NULL, owner_phone VARCHAR(20) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING', review_note VARCHAR(255),
 reviewer_id BIGINT, reviewed_at TIMESTAMP NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(reviewer_id) REFERENCES t_user(id), CHECK(rent>0), CHECK(area>0)
);
CREATE TABLE IF NOT EXISTS t_favorite (
 user_id BIGINT NOT NULL, house_id BIGINT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,house_id), FOREIGN KEY(user_id) REFERENCES t_user(id), FOREIGN KEY(house_id) REFERENCES t_house(id)
);
CREATE TABLE IF NOT EXISTS t_reservation (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, house_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 visit_time TIMESTAMP NOT NULL, phone VARCHAR(20) NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 active_slot VARCHAR(80) UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(house_id) REFERENCES t_house(id), FOREIGN KEY(user_id) REFERENCES t_user(id)
);
CREATE TABLE IF NOT EXISTS t_contract (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, house_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 rent DECIMAL(10,2) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'INTENT', terms VARCHAR(3000) NOT NULL,
 signed_at TIMESTAMP NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(house_id) REFERENCES t_house(id), FOREIGN KEY(user_id) REFERENCES t_user(id)
);
CREATE TABLE IF NOT EXISTS t_comment (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, house_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 rating INT NOT NULL, content VARCHAR(1000) NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 review_note VARCHAR(255), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(house_id) REFERENCES t_house(id), FOREIGN KEY(user_id) REFERENCES t_user(id),
 UNIQUE(house_id,user_id), CHECK(rating BETWEEN 1 AND 5)
);
CREATE TABLE IF NOT EXISTS t_message (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, house_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 content VARCHAR(1000) NOT NULL, reply VARCHAR(1000), replied_by BIGINT, replied_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(house_id) REFERENCES t_house(id), FOREIGN KEY(user_id) REFERENCES t_user(id), FOREIGN KEY(replied_by) REFERENCES t_user(id)
);
CREATE TABLE IF NOT EXISTS t_notice (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(100) NOT NULL, content VARCHAR(2000) NOT NULL,
 publisher_id BIGINT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(publisher_id) REFERENCES t_user(id)
);
CREATE TABLE IF NOT EXISTS t_audit (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT, action VARCHAR(80) NOT NULL,
 entity_type VARCHAR(32) NOT NULL, entity_id BIGINT, detail VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(actor_id) REFERENCES t_user(id)
);
